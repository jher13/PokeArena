"""Regenerate the headless Supabase engine from the game's inline script."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
source = (root / "index.html").read_text().split("<script>", 1)[1].split("</script>", 1)[0]
lines = source.splitlines()
index = next(i for i, line in enumerate(lines) if line.startswith("const pmdData="))
pmd = json.loads(lines[index].split("=", 1)[1].rstrip(";"))
# Combat uses animation durations and hitbox dimensions. Keep these while dropping
# the unused asset URLs and deduplicating sheet rectangles by dimensions.
dimensions = {}
rects = []
for motion in pmd["motions"].values():
    for directions in motion.values():
        for frames in filter(None, directions):
            for frame in frames:
                width, height = pmd["rects"][frame[0]][3:]
                key = (width, height)
                if key not in dimensions:
                    dimensions[key] = len(rects)
                    rects.append([0, 0, 0, width, height])
                frame[:] = [dimensions[key], 0, 0, frame[3]]
            if len(frames) > 1:
                frames[0][3] = sum(frame[3] for frame in frames)
                del frames[1:]
pmd["rects"], pmd["pages"], pmd["credits"] = rects, [""], {}
lines[index] = "const pmdData=" + json.dumps(pmd, separators=(",", ":")) + ";"
prefix = """// Generated by build-online-engine.py. The simulation rules come from index.html.
const makeNode = () => ({
 width:960,height:480,hidden:true,value:'',style:{},append(){},replaceChildren(){},
 setAttribute(){},cloneNode(){return makeNode();},addEventListener(){},getContext(){return {};},
});
const nodes = new Map();
const document = {
 getElementById(id) {if(!nodes.has(id))nodes.set(id,makeNode());return nodes.get(id);},
 createElement:makeNode,addEventListener(){},
};
const localStorage={getItem(){return null;},setItem(){}};
const sessionStorage=localStorage;
const window={};
const Image=class {};
const requestAnimationFrame=()=>{};
"""
source = "\n".join(lines)
source = source.replace("Math.random()", "onlineRandom()")
source = source.replace("function playSkillSound(move,event,shape) {",
    "function playSkillSound(move,event,shape) {onlineSounds.push({move,event,shape,clock});}\n"
    "function browserSkillSound(move,event,shape) {")
wrapper = (root / "supabase/functions/arena-combat/simulation.js").read_text()
(root / "supabase/functions/arena-combat/engine.js").write_text(prefix + source + "\n" + wrapper)
